export const buscarProduto = (id) => PRODUTOS.find((p) => p.id === id);

/** Foto de costas da cor escolhida (ou a principal). */
export const fotoCostas = (p, cor) => (p.imgs && p.imgs[cor]) || p.img;

/** Foto de frente da cor escolhida (ou null). */
