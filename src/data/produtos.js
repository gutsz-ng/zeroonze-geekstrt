/** Até 3 relacionados: primeiro a mesma categoria, depois as outras. */
export function relacionados(produto, quantidade = 3) {
  const outros = PRODUTOS.filter((x) => x.id !== produto.id);
  return [
    ...outros.filter((x) => x.categoria === produto.categoria),
    ...outros.filter((x) => x.categoria !== produto.categoria),
  ].slice(0, quantidade);
}
